import i18n from 'i18next';
import { initReactI18next } from 'react-i18next';

function getInitialLanguage(): 'en' | 'ar' {
  if (typeof window === 'undefined') return 'en';
  try {
    return window.localStorage.getItem('wasl-language') === 'ar' ? 'ar' : 'en';
  } catch {
    return 'en';
  }
}

i18n.on('languageChanged', (language) => {
  if (typeof window === 'undefined') return;
  try {
    if (language.startsWith('ar')) window.localStorage.setItem('wasl-language', 'ar');
    else if (language.startsWith('en')) window.localStorage.setItem('wasl-language', 'en');
  } catch {
    // Language switching still works when browser storage is unavailable.
  }
});

